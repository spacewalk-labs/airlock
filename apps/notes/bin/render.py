#!/usr/bin/env python3
"""Render Notes runtime, hub, and editor-supervisor configuration."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def render_unit(plan_path: Path, silverbullet: Path, supervisor: Path) -> str:
    return f"""[Unit]
Description=airlock notes editor supervisor (owner-only behind hub gate)
After=network.target

[Service]
Type=simple
Environment=HOME=%h
Environment=XDG_CONFIG_HOME=%h/.config
Environment=SB_SHELL_BACKEND=off
Environment=SB_RUNTIME_API=0
Environment=\"AIRLOCK_NOTES_PLAN={plan_path}\"
Environment=\"AIRLOCK_NOTES_SILVERBULLET_BIN={silverbullet}\"
ExecStart=/usr/bin/python3 {supervisor}
Restart=on-failure
RestartSec=3
UMask=0077
MemoryMax=2G
TasksMax=1024
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"""


def render_hub(plan: dict) -> str:
    blocks = [
        "# notes same-origin ingress — generated by apps/notes/install.sh",
        "location ^~ /notes/ {",
        "    if ($owner_ok = 0) { return 403; }",
        f"    proxy_pass http://127.0.0.1:{plan['reader_port']}/;",
        "    proxy_http_version 1.1;",
        "    proxy_set_header Host $host;",
        "    proxy_set_header X-Forwarded-Proto https;",
        "    proxy_read_timeout 300s;",
        "    add_header Cache-Control \"no-store\" always;",
        "}",
    ]
    for vault in plan["vaults"]:
        if not vault["writable"]:
            continue
        blocks.extend(
            [
                "",
                f"location ^~ {vault['editor_path']} {{",
                "    if ($owner_ok = 0) { return 403; }",
                f"    proxy_pass http://127.0.0.1:{vault['editor_port']};",
                "    proxy_http_version 1.1;",
                "    proxy_set_header Host $host;",
                "    proxy_set_header X-Forwarded-Proto https;",
                "    proxy_set_header Upgrade $http_upgrade;",
                "    proxy_set_header Connection $connection_upgrade;",
                "    proxy_read_timeout 86400s;",
                "}",
            ]
        )
    return "\n".join(blocks) + "\n"


def render_router(plan: dict, uid: int, gid: int) -> str:
    ids = [vault["id"] for vault in plan["vaults"]]
    default = plan["default_vault"]
    query_rows = "\n".join(f"        {vault_id} {vault_id};" for vault_id in ids)
    cookie_rows = query_rows
    backend_rows = "\n".join(
        f"        {vault_id} unix:/run/airlock-notes/{vault_id}/fpm.sock;"
        for vault_id in ids
    )
    return rf"""# generated by apps/notes/bin/render.py; do not edit
pid /tmp/nginx.pid;
error_log /dev/stderr info;
events {{ worker_connections 256; }}
http {{
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    access_log /dev/stdout;
    client_body_temp_path /tmp/client_body;
    proxy_temp_path /tmp/proxy;
    fastcgi_temp_path /tmp/fastcgi;
    uwsgi_temp_path /tmp/uwsgi;
    scgi_temp_path /tmp/scgi;

    map $arg_vault $notes_query {{
        default '';
        '' {default};
{query_rows}
    }}
    map $cookie_notes_vault $notes_cookie {{
        default {default};
{cookie_rows}
    }}
    map $arg_vault $notes_has_query {{ default 1; '' 0; }}
    map "$notes_has_query:$notes_query" $notes_bad_query {{ default 0; ~^1:$ 1; }}
    map $notes_has_query $notes_vault {{ default $notes_query; 0 $notes_cookie; }}
    map $notes_vault $notes_backend {{
        default '';
{backend_rows}
    }}
    map $notes_has_query $notes_cookie_header {{
        default "notes_vault=$notes_query; Path=/notes/; Secure; SameSite=Lax";
        0 '';
    }}

    server {{
        listen 127.0.0.1:{plan['reader_port']};
        server_name _;
        root /var/www/perlite;
        index index.php;
        add_header Set-Cookie $notes_cookie_header always;
        add_header X-Notes-Vault $notes_vault always;
        add_header Cache-Control "no-store, no-cache, must-revalidate" always;
        if ($notes_bad_query) {{ return 400; }}

        location = /_obs/vaults.json {{ try_files /_obs/vaults.json =404; }}
        location = /_obs/edit-jump.js {{ try_files /_obs/edit-jump.js =404; }}
        location ~ (^|/)\. {{ deny all; }}
        location ~* ^/notes/.+\.(png|jpe?g|gif|bmp|tiff?|webp|svg|pdf|mp4|m4a)$ {{
            rewrite ^ /_obs/raw.php last;
        }}
        location ~ \.php$ {{
            try_files $uri =404;
            include /etc/nginx/fastcgi_params;
            fastcgi_pass $notes_backend;
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_param REQUEST_URI $request_uri;
            fastcgi_read_timeout 300s;
            sub_filter_once on;
            sub_filter '<script src="/notes/.js/perlite.js"></script>' '<script src="/notes/.js/perlite.js"></script><script src="/notes/_obs/edit-jump.js" defer></script>';
        }}
        location / {{ try_files $uri $uri/ /index.php?$args; }}
        location ~ \.(md|json)$ {{ deny all; }}
    }}
}}
"""


def render_fpm(uid: int, gid: int) -> str:
    return f"""[global]
daemonize = no
error_log = /proc/self/fd/2

[www]
listen = /run/airlock-notes/fpm.sock
listen.mode = 0660
pm = dynamic
pm.max_children = 4
pm.start_servers = 1
pm.min_spare_servers = 1
pm.max_spare_servers = 2
clear_env = no
catch_workers_output = yes
security.limit_extensions = .php
"""


def render_jump() -> str:
    return r"""(() => {
  document.title = 'Notes';
  for (const [rel, href] of [
    ['icon', '/assets/app-icons/notes.svg'],
    ['apple-touch-icon', '/assets/app-icons/notes.png']
  ]) {
    let link = document.querySelector(`link[rel="${rel}"]`);
    if (!link) {
      link = document.createElement('link');
      link.rel = rel;
      document.head.appendChild(link);
    }
    link.href = href;
  }
  const cookie = Object.fromEntries(document.cookie.split(';').map(v => v.trim().split('=')));
  fetch('/notes/_obs/vaults.json', {credentials: 'same-origin'})
    .then(r => { if (!r.ok) throw new Error(`registry ${r.status}`); return r.json(); })
    .then(registry => {
      const query = new URLSearchParams(location.search).get('vault');
      const id = query || cookie.notes_vault || registry.default_vault;
      const vault = registry.vaults.find(v => v.id === id);
      if (!vault || !vault.writable || !vault.editor_path) return;
      const link = document.createElement('a');
      link.href = vault.editor_path;
      link.textContent = 'Edit';
      link.setAttribute('aria-label', `Edit ${vault.label} in SilverBullet`);
      Object.assign(link.style, {
        position: 'fixed', right: '1rem', bottom: '1rem', zIndex: '2147483647',
        padding: '.55rem .8rem', borderRadius: '.5rem', color: 'white',
        background: '#4338ca', textDecoration: 'none', font: '600 14px system-ui'
      });
      document.body.appendChild(link);
    })
    .catch(error => console.error('notes editor link:', error));
})();
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--unit", type=Path, required=True)
    parser.add_argument("--fragment", type=Path, required=True)
    parser.add_argument("--runtime-plan", type=Path, required=True)
    parser.add_argument("--silverbullet", type=Path, required=True)
    parser.add_argument("--supervisor", type=Path, required=True)
    parser.add_argument("--uid", type=int, required=True)
    parser.add_argument("--gid", type=int, required=True)
    args = parser.parse_args()
    plan = json.loads(args.plan.read_text(encoding="utf-8"))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "router.conf").write_text(render_router(plan, args.uid, args.gid), encoding="utf-8")
    (args.out / "php-fpm.conf").write_text(render_fpm(args.uid, args.gid), encoding="utf-8")
    (args.out / "edit-jump.js").write_text(render_jump(), encoding="utf-8")
    args.unit.parent.mkdir(parents=True, exist_ok=True)
    args.fragment.parent.mkdir(parents=True, exist_ok=True)
    args.unit.write_text(
        render_unit(args.runtime_plan, args.silverbullet, args.supervisor), encoding="utf-8"
    )
    args.fragment.write_text(render_hub(plan), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
